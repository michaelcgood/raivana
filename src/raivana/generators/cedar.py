"""Cedar policy generator (https://www.cedarpolicy.com).

Each IR rule becomes one `permit` or `forbid` statement. Every attribute access is
guarded with `has`, so a missing attribute behaves exactly like Raivana's PDP
(equality false, negation true) instead of raising an evaluation error.

Cedar's own semantics are fixed: forbid overrides permit and the default is deny.
Policies using other combining algorithms are flagged in the output header.
"""

from __future__ import annotations

import json
from typing import Any

from ..explain import describe_rule
from ..ir import AttributeRef, CombiningAlgorithm, Condition, Effect, Operator, Policy, Rule

VAR = {"subject": "principal", "resource": "resource", "environment": "context"}


def _lit(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(int(v)) if float(v).is_integer() else str(v)
    return json.dumps(str(v))


def _ident(name: str) -> str:
    return name if name.isidentifier() else json.dumps(name)


def _access(ref: AttributeRef) -> tuple[str, str]:
    var = VAR[ref.category]
    name = ref.id
    if name.isidentifier():
        return f"{var} has {name}", f"{var}.{name}"
    q = json.dumps(name)
    return f"{var} has {q}", f"{var}[{q}]"


def cedar_condition(c: Condition) -> str:
    has, path = _access(c.attribute)
    op = c.operator
    if isinstance(c.value, AttributeRef):
        has2, path2 = _access(c.value)
        sym = {Operator.EQ: "==", Operator.IN: "==", Operator.NEQ: "==", Operator.NOT_IN: "==",
               Operator.GT: ">", Operator.GTE: ">=", Operator.LT: "<", Operator.LTE: "<="}[op]
        expr = f"({has} && {has2} && {path} {sym} {path2})"
        return f"!{expr}" if op in (Operator.NEQ, Operator.NOT_IN) else expr
    if op in (Operator.EQ, Operator.NEQ):
        expr = f"({has} && {path} == {_lit(c.values[0])})"
    elif op in (Operator.IN, Operator.NOT_IN):
        expr = f"({has} && [{', '.join(_lit(v) for v in c.values)}].contains({path}))"
    else:
        expr = f"({has} && {path} {op.symbol} {_lit(c.values[0])})"
    return f"!{expr}" if op in (Operator.NEQ, Operator.NOT_IN) else expr


class CedarGenerator:
    format = "cedar"
    extension = ".cedar"
    title = "Cedar"

    def __init__(self, dictionary: Any = None) -> None:
        self.warnings: list[str] = []

    def _rule(self, rule: Rule) -> str:
        kw = "permit" if rule.effect == Effect.PERMIT else "forbid"
        if not rule.actions:
            act = "action"
        elif len(rule.actions) == 1:
            act = f'action == Action::"{rule.actions[0]}"'
        else:
            act = "action in [" + ", ".join(f'Action::"{a}"' for a in rule.actions) + "]"
        lines = [f"// {describe_rule(rule)}"]
        if rule.source_text:
            lines.append(f"// Source: {rule.source_text}")
        lines += [f'@id("{rule.id}")', f"{kw} (", "  principal,", f"  {act},", "  resource", ")"]
        conds = [cedar_condition(c) for c in rule.all_conditions()]
        for c in rule.all_conditions():
            if isinstance(c.value, AttributeRef) and c.operator.is_ordering:
                self.warnings.append(f"{rule.id}: attribute-to-attribute ordering requires Long attributes.")
        if conds:
            lines.append("when {")
            lines.append("  " + " &&\n  ".join(conds))
            lines.append("};")
        else:
            lines[-1] += ";"
        return "\n".join(lines)

    def generate(self, policy: Policy) -> str:
        self.warnings = []
        header = [f"// Cedar policies generated by Raivana for policy '{policy.id}'",
                  f"// Fingerprint {policy.fingerprint()}",
                  "// Cedar semantics: forbid overrides permit; requests that match no permit are denied."]
        if policy.combining not in (CombiningAlgorithm.DENY_OVERRIDES, CombiningAlgorithm.DENY_UNLESS_PERMIT):
            msg = (f"Policy uses '{policy.combining.value}', but Cedar always applies forbid-overrides. "
                   "Review conflicting rules before deploying.")
            self.warnings.append(msg)
            header.append("// WARNING: " + msg)
        if policy.default_effect == Effect.PERMIT:
            msg = "Policy default is Permit, but Cedar's default is Deny."
            self.warnings.append(msg)
            header.append("// WARNING: " + msg)
        body = "\n\n".join(self._rule(r) for r in policy.rules)
        return "\n".join(header) + "\n\n" + body + "\n"
