"""Open Policy Agent (Rego) generator.

Produces a self-contained Rego module with:
  * one boolean rule per IR rule (named after the rule id),
  * `decision` -- "Permit" | "Deny" | "NotApplicable", honouring the combining algorithm,
  * `allow`    -- true iff decision == "Permit",
  * `reasons`  -- the ids of the rules that determined the decision.

Helper functions treat request attributes as single values or lists, and a
missing attribute makes equality false and negation true -- matching Raivana's PDP.
Input shape: {"subject": {...}, "action": "read", "resource": {...}, "environment": {...}}
"""

from __future__ import annotations

import json
import re
from typing import Any

from ..explain import describe_rule
from ..ir import AttributeRef, CombiningAlgorithm, Condition, Effect, Operator, Policy, Rule

HELPERS = '''
# ---------------------------------------------------------------- helpers
_as_list(x) := [] if x == null

_as_list(x) := x if is_array(x)

_as_list(x) := [x] if {
	x != null
	not is_array(x)
}

_eq(x, v) if {
	some e in _as_list(x)
	e == v
}

_in(x, s) if {
	some e in _as_list(x)
	e in s
}

_gt(x, v) if {
	some e in _as_list(x)
	e > v
}

_gte(x, v) if {
	some e in _as_list(x)
	e >= v
}

_lt(x, v) if {
	some e in _as_list(x)
	e < v
}

_lte(x, v) if {
	some e in _as_list(x)
	e <= v
}

_shares(a, b) if {
	some e in _as_list(a)
	e in _as_list(b)
}
'''


def _lit(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(str(v))


def _path(ref: AttributeRef) -> str:
    # object.get with a null default: a missing attribute is an explicit null, never "undefined".
    # (Undefined references behave surprisingly under `not`, which broke negated conditions.)
    return f'object.get(input, [{json.dumps(ref.category)}, {json.dumps(ref.id)}], null)'


def rego_condition(c: Condition) -> str:
    p = _path(c.attribute)
    op = c.operator
    if isinstance(c.value, AttributeRef):
        q = _path(c.value)
        if op in (Operator.EQ, Operator.IN):
            return f"_shares({p}, {q})"
        if op in (Operator.NEQ, Operator.NOT_IN):
            return f"not _shares({p}, {q})"
        return f"{p} {op.symbol} {q}"
    if op == Operator.EQ:
        return f"_eq({p}, {_lit(c.values[0])})"
    if op == Operator.NEQ:
        return f"not _eq({p}, {_lit(c.values[0])})"
    if op in (Operator.IN, Operator.NOT_IN):
        s = "{" + ", ".join(_lit(v) for v in c.values) + "}"
        return f"{'not ' if op == Operator.NOT_IN else ''}_in({p}, {s})"
    fn = {Operator.GT: "_gt", Operator.GTE: "_gte", Operator.LT: "_lt", Operator.LTE: "_lte"}[op]
    return f"{fn}({p}, {_lit(c.values[0])})"


def _rule_name(rule: Rule) -> str:
    name = re.sub(r"[^A-Za-z0-9_]", "_", rule.id)
    return name if not name[0].isdigit() else f"r_{name}"


class RegoGenerator:
    format = "rego"
    extension = ".rego"
    title = "OPA / Rego"

    def __init__(self, dictionary: Any = None, package: str | None = None) -> None:
        self.package = package
        self.warnings: list[str] = []

    def _rule(self, rule: Rule) -> str:
        lines = [f"# {describe_rule(rule)}"]
        if rule.source_text:
            lines.append(f"# Source: {rule.source_text}")
        body = []
        if rule.actions:
            body.append("input.action in {" + ", ".join(_lit(a) for a in rule.actions) + "}")
        body += [rego_condition(c) for c in rule.all_conditions()]
        if not body:
            body = ["true"]
        lines.append(f"{_rule_name(rule)} if {{")
        lines += [f"\t{b}" for b in body]
        lines.append("}")
        return "\n".join(lines)

    def generate(self, policy: Policy) -> str:
        self.warnings = []
        pkg = self.package or "raivana." + re.sub(r"[^a-z0-9_]", "_", policy.id.lower())
        default = "NotApplicable"
        if policy.default_effect is not None:
            default = policy.default_effect.value
        elif policy.combining == CombiningAlgorithm.DENY_UNLESS_PERMIT:
            default = "Deny"
        elif policy.combining == CombiningAlgorithm.PERMIT_UNLESS_DENY:
            default = "Permit"
        permits = [r for r in policy.rules if r.effect == Effect.PERMIT]
        denies = [r for r in policy.rules if r.effect == Effect.DENY]
        out = [f"# Rego policy generated by Raivana for policy '{policy.id}'",
               f"# Fingerprint {policy.fingerprint()} | combining: {policy.combining.value}",
               f"package {pkg}", "", "import rego.v1", "",
               'default allow := false', "",
               'allow if decision == "Permit"', ""]
        out += [self._rule(r) + "\n" for r in policy.rules]
        out.append("# ---------------------------------------------------------------- combining")
        for r in permits:
            out.append(f'permit_rules contains "{r.id}" if {_rule_name(r)}')
        for r in denies:
            out.append(f'deny_rules contains "{r.id}" if {_rule_name(r)}')
        if not permits:
            out.append("permit_rules := set()")
        if not denies:
            out.append("deny_rules := set()")
        out.append("")
        alg = policy.combining
        if alg == CombiningAlgorithm.FIRST_APPLICABLE:
            if policy.rules:
                chain = []
                for i, r in enumerate(policy.rules):
                    head = "decision :=" if i == 0 else "else :="
                    chain.append(f'{head} "{r.effect.value}" if {{\n\t{_rule_name(r)}\n}}')
                chain.append(f'else := "{default}"')
                out.append(" ".join(chain))
                rchain = []
                for i, r in enumerate(policy.rules):
                    head = "reasons :=" if i == 0 else "else :="
                    rchain.append(f'{head} ["{r.id}"] if {{\n\t{_rule_name(r)}\n}}')
                rchain.append("else := []")
                out.append(" ".join(rchain))
            else:
                out += [f'decision := "{default}"', "reasons := []"]
        else:
            deny_first = alg in (CombiningAlgorithm.DENY_OVERRIDES, CombiningAlgorithm.PERMIT_UNLESS_DENY)
            first, second = ("deny_rules", "permit_rules") if deny_first else ("permit_rules", "deny_rules")
            fe, se = ("Deny", "Permit") if deny_first else ("Permit", "Deny")
            out += [
                f'default decision := "{default}"', "",
                f'decision := "{fe}" if count({first}) > 0', "",
                f'decision := "{se}" if {{\n\tcount({first}) == 0\n\tcount({second}) > 0\n}}', "",
                "default reasons := []", "",
                f"reasons := sort([id | some id in {first}]) if count({first}) > 0", "",
                f"reasons := sort([id | some id in {second}]) if {{\n\tcount({first}) == 0\n\tcount({second}) > 0\n}}",
            ]
        out.append(HELPERS)
        return "\n".join(out)
